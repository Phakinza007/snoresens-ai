const assert = require('node:assert/strict');
const {researchScores} = require('../web/measurements.js');
const result = (starts, duration=3600, snore=900) => ({summary:{recording_seconds:duration,detected_snore_seconds:snore},snore_events:starts.map(start=>({start_seconds:start,end_seconds:start+1}))});
let scores=researchScores(result([0,10,21,121,220]));
assert.equal(scores.snore_burden.score,25);
assert.equal(scores.stii_recording.interval_count,2); // 10 and 100 excluded; 11 and 99 included
assert.equal(scores.stii_recording.score,2);
assert.equal(researchScores(result([0,11],1800)).stii_recording.score,2);
assert.equal(researchScores(result([])).stii_recording.score,0);
assert.equal(researchScores({summary:{recording_seconds:3600,detected_snore_seconds:0}}).stii_recording.score,null);
for(const item of [{},result([],0,0),result([],100,101),result([],100,-1)]) assert.equal(researchScores(item).snore_burden.score,null);
for(const starts of [[20,10],[0,0],[-1,10],[0,Infinity],[0,3600]]) assert.equal(researchScores(result(starts)).stii_recording.score,null);
assert.equal(researchScores(result([0])).stii_recording.score,0);
assert.equal(scores.pss.score,null);
assert.equal(scores.duration_points.score,75);
assert.equal(scores.pattern_points.score,50);
assert.equal(scores.pattern_points.total_intervals,4);
assert.equal(researchScores(result([0,5,10])).pattern_points.score,100);
assert.equal(researchScores(result([0,11,22])).pattern_points.score,0);
assert.equal(researchScores(result([0])).pattern_points.score,null);
assert.equal(researchScores(result([])).pattern_points.score,null);
assert.equal(researchScores(result([20,10])).pattern_points.score,null);
assert.equal(researchScores({}).duration_points.score,null);
assert.equal(scores.combined.score,62.5);
assert.deepEqual(scores.combined.weights,{duration:0.5,pattern:0.5});
assert.equal(researchScores(result([0,11],100,100)).combined.score,0);
assert.equal(researchScores(result([0,5],100,0)).combined.score,100);
assert.equal(researchScores(result([])).combined.score,null);
assert.equal(researchScores(result([0])).combined.score,null);
assert.equal(researchScores(result([0,5],100,101)).combined.score,null);
assert.equal(researchScores(result([20,10])).combined.score,null);
assert.equal(scores.combined.excluded_categories[0],'pss');
assert.match(scores.stii_recording.formula,/recording_hours/);
assert.match(scores.stii_recording.interpretation,/not AHI/);
console.log('Research scores: PASS');
